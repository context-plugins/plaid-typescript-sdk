import * as s from "../core/validation/index.js";
import type { Schema } from "../core/validation/schema.js";

/** Object representing metadata pertaining to the document. */
export type CreditDocumentMetadata = {
  /** The name of the document. */
  name: string;
  /**
   * The type of document.
   *
   * `PAYSTUB`: A paystub.
   *
   * `BANK_STATEMENT`: A bank statement.
   *
   * `US_TAX_W2`: A W-2 wage and tax statement provided by a US employer reflecting wages earned by
   * the employee.
   *
   * `US_TAX_1099_MISC`: A 1099-MISC tax form reporting miscellaneous income.
   *
   * `US_TAX_1099_K`: A 1099-K tax form reporting payment card and third-party network transactions.
   *
   * `US_STUDENT_I20`: A Certificate of Eligibility for Nonimmigrant Student Status (Form I-20)
   * issued by a US school.
   *
   * `US_MILITARY_ERAS`: An electronic Retirement Account Statement (eRAS) issued by the US
   * military.
   *
   * `US_MILITARY_LES`: A Leave and Earnings Statement (LES) issued by the US military.
   *
   * `US_MILITARY_CLES`: A Civilian Leave and Earnings Statement (CLES) issued by the US military.
   *
   * `GIG`: Used to indicate that the income is related to gig work. Does not necessarily correspond
   * to a specific document type.
   *
   * `PLAID_GENERATED_PAYSTUB_PDF`: Used to indicate that the PDF for the paystub was generated by
   * Plaid.
   *
   * `NONE`: Used to indicate that there is no underlying document for the data.
   *
   * `UNKNOWN`: Document type could not be determined.
   */
  documentType: string | null;
  /**
   * Signed URL to retrieve the document(s). The payload will be a .zip file containing the
   * document(s).
   *
   * For Payroll Income, the file type of the documents will always be PDF, and the documents may
   * not be available, in which case the field will be `null`. If you would like Plaid to generate a
   * PDF if the original is not available, contact your account manager. [Example generated pay
   * stub](https://plaid.com/documents/plaid-generated-mock-paystub.pdf).
   *
   * For Document Income, this field will not be `null`, and the file type of the underlying
   * document(s) will be the original file type uploaded by the user. For more details on available
   * file types, see the [Document Income](https://plaid.com/docs/income/document-income)
   * documentation.
   *
   * This download URL can only be used once and expires after two minutes. To generate a new
   * download URL, call `/credit/payroll_income/get` again.
   */
  downloadUrl: string | null;
  /**
   * The processing status of the document.
   *
   * `PROCESSING_COMPLETE`: The document was successfully processed.
   *
   * `DOCUMENT_ERROR`: The document could not be processed. Possible causes include: The document
   * was an unacceptable document type such as an offer letter or bank statement, the document image
   * was cropped or blurry, or the document was corrupted.
   *
   * `UNKNOWN` or `null`: An internal error occurred. If this happens repeatedly, contact support or
   * your Plaid account manager.
   */
  status: string | null;
  /** The number of pages of the uploaded document (if available). */
  pageCount?: number | null;
  /** The reason why a failure occurred during document processing (if available). */
  errorMessage?: string | null;
};

export const creditDocumentMetadataSchema: Schema<CreditDocumentMetadata> = s.object<CreditDocumentMetadata>({
  name: s.string(),
  documentType: s.nullable(s.string()),
  downloadUrl: s.nullable(s.string()),
  status: s.nullable(s.string()),
  pageCount: s.optionalNullable(s.int()),
  errorMessage: s.optionalNullable(s.string()),
  _keysMap: {
    documentType: "document_type",
    downloadUrl: "download_url",
    pageCount: "page_count",
    errorMessage: "error_message",
  },
});
