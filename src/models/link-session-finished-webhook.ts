import * as s from "../core/validation/index.js";
import type { Schema } from "../core/validation/schema.js";
import {
  webhookEnvironmentValuesSchema,
  type WebhookEnvironmentValues,
} from "./webhook-environment-values.js";

/**
 * Contains the state of a completed Link session, along with the public token(s) if available.
 *
 * By default, this webhook is sent only for sessions enabled for the Hosted Link flow (including
 * Link Recovery flows), a Multi-Item Link flow, or a Layer flow. If you would like to receive this
 * webhook for other sessions, contact your account manager or support. This enablement will also
 * enable the `EVENTS` webhook for all Link sessions and the ability to use `/link/token/get` to
 * retrieve events for non-Hosted-Link sessions.
 */
export type LinkSessionFinishedWebhook = {
  /** `LINK` */
  webhookType: string;
  /** `SESSION_FINISHED` */
  webhookCode: string;
  /** The final status of the Link session. Will always be "SUCCESS" or "EXITED". */
  status: string;
  /** The identifier for the Link session. */
  linkSessionId: string;
  /** The `link_token` used to create the Link session. */
  linkToken: string;
  /**
   * The public token generated by the Link session. This field has been deprecated; please use
   * `public_tokens` instead.
   *
   * @deprecated
   */
  publicToken?: string;
  /** The public tokens generated by the Link session. */
  publicTokens?: string[];
  /** The Plaid `user_id` of the User associated with this webhook, warning, or error. */
  userId?: string;
  /** The Plaid environment the webhook was sent from */
  environment: WebhookEnvironmentValues;
};

export const linkSessionFinishedWebhookSchema: Schema<LinkSessionFinishedWebhook> =
  s.object<LinkSessionFinishedWebhook>({
    webhookType: s.string(),
    webhookCode: s.string(),
    status: s.string(),
    linkSessionId: s.string(),
    linkToken: s.string(),
    publicToken: s.optional(s.string()),
    publicTokens: s.optional(s.array(s.string())),
    userId: s.optional(s.string()),
    environment: webhookEnvironmentValuesSchema,
    _keysMap: {
      webhookType: "webhook_type",
      webhookCode: "webhook_code",
      linkSessionId: "link_session_id",
      linkToken: "link_token",
      publicToken: "public_token",
      publicTokens: "public_tokens",
      userId: "user_id",
    },
  });
