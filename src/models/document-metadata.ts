import * as s from "../core/validation/index.js";
import type { Schema } from "../core/validation/schema.js";
import { docTypeSchema, type DocType } from "./doc-type.js";

/** An object representing metadata from the end user's uploaded document. */
export type DocumentMetadata = {
  /** The name of the document. */
  name?: string;
  /**
   * The processing status of the document.
   *
   * `PROCESSING_COMPLETE`: The document was successfully processed.
   *
   * `DOCUMENT_ERROR`: The document could not be processed. Possible causes include: The document
   * was an unacceptable document type such as an offer letter or bank statement, the document image
   * was cropped or blurry, or the document was corrupted.
   *
   * `UNKNOWN` or `null`: An internal error occurred. If this happens repeatedly, contact support or
   * your Plaid account manager.
   */
  status?: string | null;
  /** An identifier of the document that is also present in the paystub response. */
  docId?: string;
  /**
   * The type of document.
   *
   * `DOCUMENT_TYPE_PAYSTUB`: A paystub.
   *
   * `DOCUMENT_TYPE_BANK_STATEMENT`: A bank statement.
   *
   * `DOCUMENT_TYPE_US_TAX_W2`: A W-2 wage and tax statement provided by a US employer reflecting
   * wages earned by the employee.
   *
   * `DOCUMENT_TYPE_US_MILITARY_ERAS`: An electronic Retirement Account Statement (eRAS) issued by
   * the US military.
   *
   * `DOCUMENT_TYPE_US_MILITARY_LES`: A Leave and Earnings Statement (LES) issued by the US
   * military.
   *
   * `DOCUMENT_TYPE_US_MILITARY_CLES`: A Civilian Leave and Earnings Statement (CLES) issued by the
   * US military.
   *
   * `DOCUMENT_TYPE_GIG`: Used to indicate that the income is related to gig work. Does not
   * necessarily correspond to a specific document type.
   *
   * `DOCUMENT_TYPE_NONE`: Used to indicate that there is no underlying document for the data.
   *
   * `DOCUMENT_TYPE_US_TAX_1099_MISC`: A Form 1099-MISC information return reporting miscellaneous
   * income.
   *
   * `DOCUMENT_TYPE_US_TAX_1099_K`: A Form 1099-K information return reporting payment card and
   * third-party network transactions.
   *
   * `DOCUMENT_TYPE_PLAID_GENERATED_PAYSTUB_PDF`: Used to indicate that the PDF for the paystub was
   * generated by Plaid.
   *
   * `DOCUMENT_TYPE_US_STUDENT_I20`: A Form I-20 Certificate of Eligibility for Nonimmigrant Student
   * Status.
   *
   * `UNKNOWN`: Document type could not be determined.
   */
  docType?: DocType;
};

export const documentMetadataSchema: Schema<DocumentMetadata> = s.object<DocumentMetadata>({
  name: s.optional(s.string()),
  status: s.optionalNullable(s.string()),
  docId: s.optional(s.string()),
  docType: s.optional(s.lazy(() => docTypeSchema)),
  _keysMap: {
    docId: "doc_id",
    docType: "doc_type",
  },
});
