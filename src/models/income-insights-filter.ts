import * as s from "../core/validation/index.js";
import type { Schema } from "../core/validation/schema.js";

/**
 * Filters the returned income streams based on the specified income categories. If no filters are
 * requested, streams from the following default set of categories are returned:
 * - `EARNED_INCOME.*` (`EARNED_INCOME.SALARY`, `EARNED_INCOME.GIG_ECONOMY`,
 *   `EARNED_INCOME.SELF_EMPLOYED`)
 * - `BENEFITS.DISABILITY`
 * - `RETIREMENT.*` (`RETIREMENT.GOVERNMENT_DERIVED`, `RETIREMENT.PRIVATE_RETIREMENT`,
 *   `RETIREMENT.PLAN_DISTRIBUTION`)
 *
 * The final list of income categories is generated by adding the `included_categories`, then
 * removing the `excluded_categories`. Priority is given to `excluded_categories` in the case of
 * collisions.
 *
 * Filter patterns supported:
 * - `*`: All categories
 * - `PRIMARY.*`: All categories within the specified primary category
 * - `PRIMARY.SECONDARY`: A specific income category
 *
 * For a list of income categories, see the [Income V2 Category
 * Taxonomy](https://plaid.com/documents/income-v2-category-taxonomy.csv).
 */
export type IncomeInsightsFilter = {
  /** Includes income streams matching the specified categories. */
  includedCategories: string[];
  /** Excludes income streams matching the specified categories. */
  excludedCategories?: string[];
};

export const incomeInsightsFilterSchema: Schema<IncomeInsightsFilter> = s.object<IncomeInsightsFilter>({
  includedCategories: s.array(s.string()),
  excludedCategories: s.optional(s.array(s.string())),
  _keysMap: {
    includedCategories: "included_categories",
    excludedCategories: "excluded_categories",
  },
});
